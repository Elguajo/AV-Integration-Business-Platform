"""Entry page for the role workspaces (/av/...). The HTML template av.html is
generated by the frontend build (apps/av_platform/frontend); do not edit it by hand."""

import frappe

no_cache = 1


def get_context(context):
    if frappe.session.user == "Guest":
        frappe.local.flags.redirect_location = "/login?redirect-to=" + frappe.utils.quote(
            frappe.request.path if frappe.request else "/av"
        )
        raise frappe.Redirect
    context.boot = {
        "csrf_token": frappe.sessions.get_csrf_token(),
        "av_user": frappe.session.user,
    }
