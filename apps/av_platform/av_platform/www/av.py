"""/av and /av/<path>: the AV Platform shell (ADR-006).

The template av.html is generated by the frontend build (apps/av_platform/frontend); do not edit
it by hand. Users without a screen of the shell go to their start page (a moderator to the staff
list) or to Desk.
"""

import frappe

from av_platform.shell import boot, home_page, visible_views

no_cache = 1


def get_context(context):
    if frappe.session.user == "Guest":
        path = frappe.request.path if getattr(frappe.local, "request", None) else "/av"
        frappe.local.flags.redirect_location = "/login?redirect-to=" + frappe.utils.quote(path)
        raise frappe.Redirect(302)
    if not visible_views():
        frappe.local.flags.redirect_location = "/" + (home_page() or "desk")
        raise frappe.Redirect(302)
    context.boot = {"csrf_token": frappe.sessions.get_csrf_token(), "av_boot": boot()}
